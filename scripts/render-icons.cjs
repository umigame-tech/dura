// Renders the SVG ICON in src/routes/assets.ts to the PNGs in src/routes/icons.ts.
// Run it after changing ICON: node scripts/render-icons.cjs
// It needs Playwright with Chromium (npx playwright install chromium), which is
// not a dependency of the project.
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");

const assets = fs.readFileSync(path.join(__dirname, "../src/routes/assets.ts"), "utf8");
const icon = assets.match(/const ICON = `(<svg[\s\S]*?<\/svg>)`;/)[1];
const background = icon.match(/<rect [^>]*\/>/)[0];
// apple-touch and maskable icons are full-bleed squares; the badge is the mark alone
// in white, since Android uses only its alpha channel.
const fullBleed = icon.replace(background, background.replace(/ rx="[^"]*"/, ""));
const badge = icon.replace(background, "").replace(/fill="#(?!fff")[0-9a-f]{6}"/g, 'fill="#fff"');

const variants = [
  ["ICON_192", icon, 192],
  ["ICON_512", icon, 512],
  ["ICON_MASKABLE_512", fullBleed, 512],
  ["APPLE_TOUCH_ICON", fullBleed, 180],
  ["BADGE_96", badge, 96],
];

(async () => {
  const browser = await chromium.launch();
  const lines = [];
  for (const [name, svg, size] of variants) {
    const page = await browser.newPage({ viewport: { width: size, height: size } });
    await page.setContent(`<body style="margin:0">${svg.replace("<svg ", `<svg width="${size}" height="${size}" `)}</body>`);
    const png = await page.locator("svg").screenshot({ omitBackground: true });
    lines.push(`export const ${name} = "${png.toString("base64")}";`);
    await page.close();
  }
  await browser.close();
  const header = [
    "// PNG renderings of ICON in assets.ts, for clients that do not accept SVG icons",
    "// (iOS apple-touch-icon, Android manifest icons and notification badges).",
    "// Generated by scripts/render-icons.cjs; run it again when ICON changes.",
    "",
  ];
  fs.writeFileSync(path.join(__dirname, "../src/routes/icons.ts"), [...header, ...lines, ""].join("\n"));
})();
